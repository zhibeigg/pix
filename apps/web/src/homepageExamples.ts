export function getHomepageExampleItemSubject(example: HomepageExample, index: number, language: 'zh-CN' | 'en') {
  const subject = homepageExampleItemSubjects[example.id]?.[index]
  const fallbackSlot = String(index + 1).padStart(2, '0')
  if (language === 'en') return subject?.en || `${deriveEnglishTheme(example)} icon ${fallbackSlot}`
  return subject?.zh || `${example.theme}图标 ${fallbackSlot}`
}

export function getHomepageExampleItemSubjectPrompt(example: HomepageExample, index: number, language: 'zh-CN' | 'en') {
  const subject = getHomepageExampleItemSubject(example, index, language)
  if (language === 'en') {
    return `${subject}, ${deriveEnglishTheme(example)} themed single prop, emphasize its recognizable shape, material, and game-inventory readability`
  }
  return `${subject}，${example.theme}题材单个道具，突出可识别造型、材质特征和背包图标可读性`
}

export function getHomepageExampleItemSubjectList(example: HomepageExample, language: 'zh-CN' | 'en') {
  return Array.from({ length: itemSlotCount }, (_, index) => getHomepageExampleItemSubjectPrompt(example, index, language))
}

export function buildHomepageExampleItemPrompt(example: HomepageExample, index: number, variant: HomepageExampleItemVariant, language: 'zh-CN' | 'en') {
  const subjectPrompt = getHomepageExampleItemSubjectPrompt(example, index, language)
  if (language === 'en') {
    const sizeLead = variant === 'original64' ? '64×64 pixel game item icon' : '32×32 outline pixel game item icon'
    return `${sizeLead}, retro 8-bit pixel art style, single prop, theme: ${deriveEnglishTheme(example)}, subject: ${subjectPrompt}, clean solid background, clear silhouette, sharp pixel blocks, crisp outline, limited palette, no anti-aliasing, square canvas, transparent PNG game asset.`
  }
  const sizeLead = variant === 'original64' ? '64×64 像素游戏物品图标' : '32×32 outline 像素游戏物品图标'
  return `${sizeLead}，复古 8 位像素风格，单个道具，题材：${example.theme}，主体：${subjectPrompt}，纯色干净背景，轮廓清晰，色块分明，线条锐利，有限调色板，无抗锯齿，正方形画幅，透明 PNG 游戏素材。`
}

