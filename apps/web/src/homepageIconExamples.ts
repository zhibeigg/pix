const homepageItemSlotCount = 8

export const homepageExampleItemIcons: HomepageExampleItemIcon[] = homepageExamples.flatMap((example) =>
  Array.from({ length: homepageItemSlotCount }, (_, index) => {
    const slotLabel = String(index + 1).padStart(2, '0')
    const file = `${example.id}_item_${slotLabel}.png`
    const [width, height] = homepageExampleItemIconDimensions[file] ?? [0, 0]
    return {
      id: `${example.id}_${slotLabel}`,
      exampleId: example.id,
      slot: index,
      slotLabel,
      file,
      src: `/homepage-examples/items/${file}`,
      width,
      height,
    }
  }),
)

export const homepageExampleIconSizes = Array.from(
  new Set(homepageExampleItemIcons.map((icon) => `${icon.width}x${icon.height}`)),
).sort((left, right) => Number(left.split('x')[0]) - Number(right.split('x')[0]))

const homepageIconsByExampleId = new Map<string, HomepageExampleItemIcon[]>()

for (const icon of homepageExampleItemIcons) {
  const current = homepageIconsByExampleId.get(icon.exampleId) ?? []
  current.push(icon)
  homepageIconsByExampleId.set(icon.exampleId, current)
}

export function getHomepageIconsForExample(exampleId: string) {
  return homepageIconsByExampleId.get(exampleId) ?? []
}

